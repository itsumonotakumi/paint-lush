const byId: ReadonlyMap<string, CharacterDef> = new Map(CHARACTERS.map((def) => [def.id, def]));

/** Unknown ids fall back to the default roster entry, never to undefined. */
export function getCharacter(id: string): CharacterDef {
  const found = byId.get(id);
  if (found !== undefined) return found;
  const fallback = byId.get(DEFAULT_CHARACTER_ID);
  if (fallback === undefined) throw new Error('roster is missing its default character');
  return fallback;
}
